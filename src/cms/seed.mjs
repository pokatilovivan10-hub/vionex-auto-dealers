import { createBlock } from './block-definitions.mjs';

function block(type, data = {}, options = {}) {
  const value = createBlock(type);
  value.data = { ...value.data, ...data };
  if (options.enabled === false) value.enabled = false;
  if (options.variant) value.variant = options.variant;
  return value;
}

function document(blocks) {
  return { schemaVersion: 1, blocks };
}

